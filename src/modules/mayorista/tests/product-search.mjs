import assert from 'node:assert/strict';
import {performance} from 'node:perf_hooks';
import {buildProductIndex, customerFrequencies, searchProducts} from '../vendedor/product-search.mjs';
import {largeSellerCatalog} from './product-search-fixture.mjs';
const catalog = largeSellerCatalog(), index = buildProductIndex(catalog.productos, catalog.precios.filter(p => p.listaId === 'l1'));
assert.equal(index.length, 5000);
for (const [query, id] of [['acei gir','p0'],['AZUCAR','p1'],['sol sur','p0'],['INT-04999','p4999'],['7790000004999','p4999'],['Mercaderia 4999','p4999']]) assert.equal(searchProducts(index, query)[0]?.product.id, id, query);
assert.equal(searchProducts(index, 'inexistente').length, 0);
assert.equal(searchProducts(index, 'art').length, 10);
const frequencies = customerFrequencies([{clienteId:'c1',lineas:[{productoId:'p4999'},{productoId:'p4999'}]},{clienteId:'c2',lineas:[{productoId:'p1'}]}], 'c1');
assert.equal(frequencies.get('p4999'), 1);
assert.equal(frequencies.has('p1'), false);
assert.equal(searchProducts(index, '', frequencies)[0].product.id, 'p4999');
assert.equal(searchProducts(index, 'azucar', frequencies)[0].product.id, 'p1');
assert.equal(buildProductIndex([{id:'off',activo:false},{id:'no-price'}],[{id:'x',productoId:'off',unidadesBase:1,precio:1}]).length, 0);
const duplicate = buildProductIndex([{id:'partial',nombre:'7790000000000 promoción'},{id:'exact',codigo:'7790000000000'}],[{id:'a',productoId:'partial',unidadesBase:1,precio:1},{id:'b',productoId:'exact',unidadesBase:1,precio:1}]);
assert.equal(searchProducts(duplicate,'7790000000000',new Map([['partial',100]]))[0].product.id,'exact');
const durations=[];
for(let n=0;n<300;n++){const before=performance.now();searchProducts(index,['art','acei gir','marca 1','7790000004999','no existe'][n%5],frequencies);durations.push(performance.now()-before);}
durations.sort((a,b)=>a-b);
console.log(JSON.stringify({passed:true,products:5000,queries:300,nodeP95Ms:durations[Math.floor(durations.length*.95)],mobileDevice:false}));
